def log(message):
    """Log message to file and console."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    log_message = f"[{{timestamp}}] {{message}}"
    print(log_message)
    with open(LOG_FILE, 'a', encoding='utf-8') as f:
        f.write(log_message + "\\n")


def print_file(file_path, copies=1, duplex=False, color=False):
    """Send file to printer using Windows print command."""
    try:
        # For PDFs, use Adobe Reader or SumatraPDF if available
        if file_path.endswith('.pdf'):
            # Try SumatraPDF first (lightweight and supports command-line printing)
            sumatra_path = Path(os.environ.get('PROGRAMFILES', 'C:\\\\Program Files')) / 'SumatraPDF' / 'SumatraPDF.exe'
            if sumatra_path.exists():
                cmd = [str(sumatra_path), '-print-to', PRINTER_NAME, file_path]
                subprocess.run(cmd, check=True)
                log(f"Printed {{file_path}} using SumatraPDF")
                return True
            
            # Fallback to Adobe Reader
            adobe_paths = [
                Path(os.environ.get('PROGRAMFILES', 'C:\\\\Program Files')) / 'Adobe' / 'Acrobat Reader DC' / 'Reader' / 'AcroRd32.exe',
                Path(os.environ.get('PROGRAMFILES(X86)', 'C:\\\\Program Files (x86)')) / 'Adobe' / 'Acrobat Reader DC' / 'Reader' / 'AcroRd32.exe',
            ]
            
            for adobe_path in adobe_paths:
                if adobe_path.exists():
                    cmd = [str(adobe_path), '/t', file_path, PRINTER_NAME]
                    subprocess.run(cmd, check=True)
                    log(f"Printed {{file_path}} using Adobe Reader")
                    return True
        
        # Fallback: use Windows default print command
        os.startfile(file_path, "print")
        log(f"Printed {{file_path}} using Windows default handler")
        return True
    
    except Exception as e:
        log(f"Print error: {{str(e)}}")
        return False


def check_print_queue():
    """Poll server for pending print jobs."""
    try:
        response = requests.get(
            f"{{SERVER_URL}}/api/agent/queue/{{KIOSK_ID}}",
            timeout=5
        )
        
        if response.status_code == 200:
            jobs = response.json()
            return jobs
        else:
            return []
    
    except Exception as e:
        log(f"Queue check error: {{str(e)}}")
        return []


def update_job_status(job_id, status, error=None):
    """Update print job status on server."""
    try:
        payload = {{"status": status}}
        if error:
            payload["error"] = error
        
        requests.post(
            f"{{SERVER_URL}}/api/agent/job/{{job_id}}/status",
            json=payload,
            timeout=5
        )
    except Exception as e:
        log(f"Status update error: {{str(e)}}")


def main():
    """Main agent loop."""
    log(f"Prynt Agent started for kiosk: {{KIOSK_NAME}} ({{KIOSK_ID}})")
    log(f"Printer: {{PRINTER_NAME}}")
    log(f"Server: {{SERVER_URL}}")
    
    while True:
        try:
            # Check for pending jobs
            jobs = check_print_queue()
            
            for job in jobs:
                job_id = job.get('id')
                file_url = job.get('file_url')
                copies = job.get('copies', 1)
                duplex = job.get('duplex', False)
                color = job.get('color_mode', False)
                
                log(f"Processing job {{job_id}}")
                
                # Download file
                file_response = requests.get(f"{{SERVER_URL}}{{file_url}}", timeout=30)
                if file_response.status_code != 200:
                    log(f"Failed to download file for job {{job_id}}")
                    update_job_status(job_id, 'failed', 'File download failed')
                    continue
                
                # Save to temp file
                temp_file = AGENT_DIR / f"print_{{job_id}}.pdf"
                with open(temp_file, 'wb') as f:
                    f.write(file_response.content)
                
                # Print file
                update_job_status(job_id, 'printing')
                success = print_file(str(temp_file), copies, duplex, color)
                
                if success:
                    update_job_status(job_id, 'completed')
                    log(f"Job {{job_id}} completed successfully")
                else:
                    update_job_status(job_id, 'failed', 'Print command failed')
                    log(f"Job {{job_id}} failed")
                
                # Cleanup
                try:
                    temp_file.unlink()
                except:
                    pass
            
            # Wait before next check
            time.sleep(5)
        
        except KeyboardInterrupt:
            log("Agent stopped by user")
            break
        except Exception as e:
            log(f"Agent error: {{str(e)}}")
            time.sleep(10)


